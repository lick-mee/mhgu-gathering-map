"""Builds the plugin's icon tables, src/items.h, from the game files.

  - per item: its icon (cell of the common icon texture) and item color, from the item table;
  - the icon kinds the map shows (ore, bone, bug, herb...) and where each is: an item icon of the common icon
    texture, or the map icon texture's dropped-item marker for pickups of no gathering kind;
  - which kind a gathering spot's model looks like, and the item colors.

Usage: python tools/make_data.py [recomp folder]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata as gd

# The map_icon layout's texture table: 2 = the common icon texture (512x1024 layout, item icon n in the 32-pixel
# cell (n % 10, n // 10); the first rows' cells past 10 hold other icons), 3 = the map icon texture (128x256).
TEX_CMN, TEX_MAP = 2, 3
CMN_CELL, CMN_ROW = 32, 10
OTHER_RECT = (0, 120, 24, 144)  # the map icon texture's dropped-item marker (em_otosimono)

# Item icons the map shows, as kinds 1..; kind 0 is the marker for other pickups (crates, barrels, ammo...).
ICON_MUSHROOM, ICON_HERB, ICON_HONEY, ICON_BUG, ICON_WEB, ICON_BERRY, ICON_ORE, ICON_BONE = 1, 3, 5, 6, 7, 8, 9, 14
ICON_EGG, ICON_DUNG, ICON_BAIT, ICON_STONE, ICON_WOOD = 15, 16, 18, 42, 93
KINDS = [None, ICON_ORE, ICON_BONE, ICON_BUG, ICON_HERB, ICON_MUSHROOM, ICON_HONEY, ICON_BERRY, ICON_WEB,
         ICON_EGG, ICON_DUNG, ICON_STONE, ICON_BAIT, ICON_WOOD]
# What a spot's model looks like, where that settles it.
MODEL_KIND = {1: ICON_BERRY, 2: ICON_BERRY, 3: ICON_HERB, 4: ICON_HERB, 5: ICON_MUSHROOM, 6: ICON_MUSHROOM,
              7: ICON_BONE, 8: ICON_BONE, 9: ICON_ORE, 10: ICON_ORE, 11: ICON_HONEY, 12: ICON_HONEY, 20: ICON_WEB}
MODELS = 64

# Item colors (the item table's color index), as the game tints item icons.
COLORS = [
    (235, 235, 235), (230, 64, 64), (96, 200, 80), (80, 128, 245), (240, 220, 64), (175, 95, 225),
    (110, 205, 245), (245, 145, 45), (245, 125, 185), (180, 230, 70), (165, 165, 165), (175, 125, 75),
    (70, 205, 190), (125, 80, 170), (200, 60, 60), (215, 185, 120),
]
COLOR_GRAY = 10


def kind_icon(icon):
    if icon is None:
        return TEX_MAP, OTHER_RECT
    x, y = icon % CMN_ROW * CMN_CELL, icon // CMN_ROW * CMN_CELL
    return TEX_CMN, (x, y, x + CMN_CELL, y + CMN_CELL)


def write_header(root, path):
    items = gd.item_table(root)
    w = lambda f, rows: f.write(''.join('    ' + r + ',\n' for r in rows) + '};\n\n')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/make_data.py from the item table. Do not edit.\n')
        f.write('#define KIND_OTHER 0\n#define KIND_ORE %d\n#define KIND_BUG %d\n#define KIND_BONE %d\n'
                % (KINDS.index(ICON_ORE), KINDS.index(ICON_BUG), KINDS.index(ICON_BONE)))
        f.write('#define KIND_COUNT %d\n#define COLOR_COUNT %d\n#define COLOR_GRAY %d\n#define ITEM_COUNT %d\n#define MODEL_COUNT %d\n\n'
                % (len(KINDS), len(COLORS), COLOR_GRAY, len(items), MODELS))
        f.write('// Per kind: the map_icon texture (2 common icons, 3 map icons), its cut (x0, y0, x1, y1, in that\n'
                "// texture's layout units) and the item icon it is (0xFF for none).\n")
        f.write('static const IconCut g_kinds[KIND_COUNT] = {\n')
        w(f, ['{%d, {%d, %d, %d, %d}, %d}' % ((kind_icon(k)[0],) + kind_icon(k)[1] + (0xFF if k is None else k,))
              for k in KINDS])
        f.write('// Item colors (RGBA, as the texture object stores them).\n')
        f.write('static const u32 g_colors[COLOR_COUNT] = {\n')
        w(f, ['0x%08X' % (0xFF000000 | b << 16 | g << 8 | r) for r, g, b in COLORS])
        f.write('// Per item: its icon and color index.\n')
        f.write('static const u8 g_items[ITEM_COUNT][2] = {\n')
        w(f, [' '.join('{%d, %d},' % it for it in items[i:i + 12]).rstrip(',') for i in range(0, len(items), 12)])
        f.write('// Per item icon: the kind showing it (KIND_OTHER if none).\n')
        f.write('static const u8 g_icon_kind[256] = {\n')
        kind = [KINDS.index(i) if i in KINDS else 0 for i in range(256)]
        w(f, [', '.join('%d' % k for k in kind[i:i + 32]) for i in range(0, 256, 32)])
        f.write("// Per spot model: the kind it looks like (KIND_OTHER: decide by its items).\n")
        f.write('static const u8 g_model_kind[MODEL_COUNT] = {\n')
        mk = [KINDS.index(MODEL_KIND[m]) if m in MODEL_KIND else 0 for m in range(MODELS)]
        w(f, [', '.join('%d' % k for k in mk[i:i + 32]) for i in range(0, MODELS, 32)])
    print('wrote %s (%d items)' % (os.path.normpath(path), len(items)))


def main(args):
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.abspath(args[0] if args else os.path.join(here, '..', '..'))
    if not os.path.isdir(os.path.join(root, 'data', gd.NATIVE)):
        raise SystemExit('%s is not an MHGU Recomp folder (it has no data\\romfs\\nativeNX)' % root)
    write_header(root, os.path.join(here, '..', 'src', 'items.h'))


if __name__ == '__main__':
    main(sys.argv[1:])
