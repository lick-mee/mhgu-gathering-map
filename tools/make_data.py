"""Builds the mod's map icons from your game files, and (for development) the plugin's point table.

  <recomp>/mods/zzz-gather-map/romfs/nativeNX/eng/arc/quest_eng.arc: the (English) quest archive with
    - the map icon texture (HD_map_icon) given the gathering item icons (ore, bone, bug...), copied from the common
      icon texture into its free space at map icon size, and
    - the map icon layout (GUI\\01_quest\\map\\map_icon) given one sequence per icon kind and item color.
    Each is built from the archive the game would load otherwise (another mod's, e.g. an HD UI mod, else the
    game's), so run this again after updating such a mod. Game files can't be shipped, so the release runs this
    (setup.bat) on the player's own.
  src/points.h, with --header: every map's gathering points (map, area, world position) and the icon each shows.

Usage: python tools/make_data.py [--header] [recomp folder]
"""
import os
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata as gd

MOD = 'zzz-gather-map'  # after other mods in folder order, so its quest archives win
LANGUAGES = ['eng']  # English game text only
MAP_ICON = '%s\\GUI\\01_quest\\map\\map_icon'
MAP_TEXTURE = '%s\\GUI\\99_texture\\map\\HD_map_icon_GSM_NOMIP'
CMN_TEXTURE = '%s\\GUI\\99_texture\\HD_cmn_icon_GSM_NOMIP'
TYPE_TEX = 0x241F5DEB
# Sequence FIRST_SEQUENCE + kind * len(COLORS) + color shows icon kind (index into KINDS) in item color color. The
# game's map icon sequences are 1000000..1000024. The numbering is fixed, so a plugin built anywhere matches an
# archive built from anyone's files.
FIRST_SEQUENCE = 1000100

# Layout sizes (the GUI's units): the map icon texture is 128x256 with 24-pixel icons, the common icon texture
# 512x1024 with item icon n in the 32-pixel cell (n % 10, n // 10); the first rows' cells past 10 hold other
# icons. HD textures are bigger, laid out the same.
MAP_LAYOUT_W, ICON, CMN_LAYOUT_W, CMN_CELL, CMN_ROW = 128, 24, 512, 32, 10
# Free cells of the map icon texture for gamedata.KINDS, in that order (layout units).
CELLS = [(x, 145) for x in range(0, 120, 24)] + [(x, 169) for x in range(0, 120, 24)] + [(x, 193) for x in range(0, 72, 24)]
OTHER_RECT = (0, 120, 24, 144)  # the game's dropped-item marker (em_otosimono), for spots of no gathering kind
KINDS = [None] + gd.KINDS  # 0: other pickups (crates, barrels, ammo...)

# Item colors (the item table's color index), as the game tints item icons.
COLORS = [
    (235, 235, 235), (230, 64, 64), (96, 200, 80), (80, 128, 245), (240, 220, 64), (175, 95, 225),
    (110, 205, 245), (245, 145, 45), (245, 125, 185), (180, 230, 70), (165, 165, 165), (175, 125, 75),
    (70, 205, 190), (125, 80, 170), (200, 60, 60), (215, 185, 120),
]


def arc_entry(arc, name, type_hash):
    for _off, n, th, csize, _dsize, data_off in gd.arc_entries(arc):
        if n == name and th == type_hash:
            return zlib.decompress(arc[data_off:data_off + csize])
    raise SystemExit('no %s in the archive' % name)


def add_icons(map_tex, cmn_tex):
    """The map icon texture with the gathering icons in CELLS."""
    mw, mh, mpx = gd.tex_rgba(map_tex)
    cw, _ch, cpx = gd.tex_rgba(cmn_tex)
    ms, cs = mw / MAP_LAYOUT_W, cw / CMN_LAYOUT_W
    size, src = round(ICON * ms), round(CMN_CELL * cs)
    for kind, (x, y) in zip(gd.KINDS, CELLS):
        dx, dy = round(x * ms), round(y * ms)
        for j in range(size):
            row = mpx[((dy + j) * mw + dx) * 4:((dy + j) * mw + dx + size) * 4]
            assert not any(row[3::4]), 'map icon texture cell (%d, %d) is not free' % (x, y)
        gd.blit_scaled(mpx, mw, dx, dy, size, cpx, cw, kind % CMN_ROW * src, kind // CMN_ROW * src, src)
    return gd.tex_with_rgba(map_tex, mw, mh, mpx)


def kind_rects():
    cell = dict(zip(gd.KINDS, CELLS))
    return [OTHER_RECT if k is None else cell[k] + (cell[k][0] + ICON, cell[k][1] + ICON) for k in KINDS]


def write_header(root, path):
    stages = gd.stage_points(root, gd.item_table(root))
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write("// Generated by tools/make_data.py --header from the maps' gathering points (IPS) and item lots (IPL).\n")
        f.write('// Do not edit. kind: 0 = other pickup (crates, barrels, ammo...), then the gathering kinds; map_icon\n')
        f.write('// sequence FIRST_SEQUENCE + kind * COLOR_COUNT + color shows it.\n')
        f.write('#define FIRST_SEQUENCE %d\n#define KIND_COUNT %d\n#define COLOR_COUNT %d\n\n'
                % (FIRST_SEQUENCE, len(KINDS), len(COLORS)))
        f.write('static const GatherPoint g_points[] = {\n')
        count, first, most = 0, {}, 0
        for n, pts in stages:
            first[n] = (count, len(pts))
            most = max(most, len(pts))
            for p, (kind, color) in pts:
                f.write('    {%d, %d, %d, %d, {%.1ff, %.1ff, %.1ff}},\n'
                        % ((n, p['area'], KINDS.index(kind), color % len(COLORS)) + p['pos']))
                count += 1
        f.write('};\n\n')
        f.write('// Per map number: index of its first point and how many it has.\n')
        f.write('#define MAP_COUNT 28\n#define MAX_MAP_POINTS %d\n' % most)
        f.write('static const u16 g_map_points[MAP_COUNT][2] = {\n')
        for n in range(28):
            f.write('    {%d, %d},\n' % first.get(n, (0, 0)))
        f.write('};\n\n')
        f.write('// Per kind: its cut of the map icon texture (x0, y0, x1, y1, layout units).\n')
        f.write('static const float g_kind_rects[KIND_COUNT][4] = {\n')
        for r in kind_rects():
            f.write('    {%d, %d, %d, %d},\n' % r)
        f.write('};\n')
    print('wrote %s (%d points)' % (os.path.normpath(path), count))


def write_archive(root, lang):
    rel = os.path.join(gd.NATIVE, lang, 'arc', 'quest_%s.arc' % lang)
    src = gd.source(root, rel, skip_mod=MOD)
    if not os.path.isfile(src):
        return False
    arc = open(src, 'rb').read()
    resident = gd.source(root, os.path.join(gd.NATIVE, lang, 'arc', 'resident_%s.arc' % lang), skip_mod=MOD)
    cmn = arc_entry(open(resident, 'rb').read(), CMN_TEXTURE % lang, TYPE_TEX)
    tex = add_icons(arc_entry(arc, MAP_TEXTURE % lang, TYPE_TEX), cmn)
    icons = [(rect, color + (255,)) for rect in kind_rects() for color in COLORS]
    gui = gd.add_icon_sequences(arc_entry(arc, MAP_ICON % lang, gd.TYPE_GUI), icons, FIRST_SEQUENCE)
    arc = gd.replace_in_arc(arc, MAP_TEXTURE % lang, TYPE_TEX, tex)
    arc = gd.replace_in_arc(arc, MAP_ICON % lang, gd.TYPE_GUI, gui)
    dst = os.path.join(root, 'mods', MOD, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, 'wb').write(arc)
    print('%s: built from %s' % (lang, os.path.relpath(src, root)))
    return True


def main(args):
    here = os.path.dirname(os.path.abspath(__file__))
    rest = [a for a in args if a != '--header']
    root = os.path.abspath(rest[0] if rest else os.path.join(here, '..', '..'))
    if not os.path.isdir(os.path.join(root, 'data', gd.NATIVE)):
        raise SystemExit('%s is not an MHGU Recomp folder (it has no data\\romfs\\nativeNX)' % root)
    if '--header' in args:
        write_header(root, os.path.join(here, '..', 'src', 'points.h'))
    done = [lang for lang in LANGUAGES if write_archive(root, lang)]
    print('map icons ready (%s) in %s' % (', '.join(done), os.path.join(root, 'mods', MOD)))


if __name__ == '__main__':
    main(sys.argv[1:])
