"""Builds the plugin's point table, src/points.h, from the game files.

Every map's gathering points (map, area, world position) with the kind of icon (ore, bone, bug...) and item color
each one shows, and per kind where the icon is: an item icon of the game's common icon texture, or the map icon
texture's dropped-item marker for pickups of no gathering kind.

Usage: python tools/make_data.py [recomp folder]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata as gd

# The map_icon layout's texture table: 2 = the common icon texture (512x1024 layout, item icon n in the 32-pixel
# cell (n % 10, n // 10); the first rows' cells past 10 hold other icons), 3 = the map icon texture (128x256).
TEX_CMN, TEX_MAP = 2, 3
CMN_CELL, CMN_ROW = 32, 10
OTHER_RECT = (0, 120, 24, 144)  # the map icon texture's dropped-item marker (em_otosimono)
KINDS = [None] + gd.KINDS  # 0: other pickups (crates, barrels, ammo...)

# Item colors (the item table's color index), as the game tints item icons.
COLORS = [
    (235, 235, 235), (230, 64, 64), (96, 200, 80), (80, 128, 245), (240, 220, 64), (175, 95, 225),
    (110, 205, 245), (245, 145, 45), (245, 125, 185), (180, 230, 70), (165, 165, 165), (175, 125, 75),
    (70, 205, 190), (125, 80, 170), (200, 60, 60), (215, 185, 120),
]


def kind_icon(kind):
    if kind is None:
        return TEX_MAP, OTHER_RECT
    x, y = kind % CMN_ROW * CMN_CELL, kind // CMN_ROW * CMN_CELL
    return TEX_CMN, (x, y, x + CMN_CELL, y + CMN_CELL)


def write_header(root, path):
    stages = gd.stage_points(root, gd.item_table(root))
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write("// Generated by tools/make_data.py from the maps' gathering points (IPS) and item lots (IPL). Do not edit.\n")
        f.write('// kind: 0 = other pickup (crates, barrels, ammo...), then the gathering kinds; color: g_colors index.\n')
        f.write('#define KIND_OTHER 0\n#define KIND_COUNT %d\n#define COLOR_COUNT %d\n\n' % (len(KINDS), len(COLORS)))
        f.write('static const GatherPoint g_points[] = {\n')
        count, first, most = 0, {}, 0
        for n, pts in stages:
            first[n] = (count, len(pts))
            most = max(most, len(pts))
            for p, (kind, color) in pts:
                f.write('    {%d, %d, %d, %d, {%.1ff, %.1ff, %.1ff}},\n'
                        % ((n, p['area'], KINDS.index(kind), color % len(COLORS)) + p['pos']))
                count += 1
        f.write('};\n\n')
        f.write('// Per map number: index of its first point and how many it has.\n')
        f.write('#define MAP_COUNT 28\n#define MAX_MAP_POINTS %d\n' % most)
        f.write('static const u16 g_map_points[MAP_COUNT][2] = {\n')
        for n in range(28):
            f.write('    {%d, %d},\n' % first.get(n, (0, 0)))
        f.write('};\n\n')
        f.write("// Per kind: the map_icon texture (2 common icons, 3 map icons) and its cut (x0, y0, x1, y1, in that\n")
        f.write("// texture's layout units).\n")
        f.write('static const IconCut g_kinds[KIND_COUNT] = {\n')
        for k in KINDS:
            tex, r = kind_icon(k)
            f.write('    {%d, {%d, %d, %d, %d}},\n' % ((tex,) + r))
        f.write('};\n\n')
        f.write('// Item colors (RGBA, as the texture object stores them).\n')
        f.write('static const u32 g_colors[COLOR_COUNT] = {\n')
        for r, g, b in COLORS:
            f.write('    0x%08X,\n' % (0xFF000000 | b << 16 | g << 8 | r))
        f.write('};\n')
    print('wrote %s (%d points)' % (os.path.normpath(path), count))


def main(args):
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.abspath(args[0] if args else os.path.join(here, '..', '..'))
    if not os.path.isdir(os.path.join(root, 'data', gd.NATIVE)):
        raise SystemExit('%s is not an MHGU Recomp folder (it has no data\\romfs\\nativeNX)' % root)
    write_header(root, os.path.join(here, '..', 'src', 'points.h'))


if __name__ == '__main__':
    main(sys.argv[1:])
